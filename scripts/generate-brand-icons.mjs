// Extracts the handful of brand marks the site uses from `simple-icons`
// so the full icon set never ships to the browser.
// Run with: pnpm icons
import { writeFile } from 'node:fs/promises';
import * as si from 'simple-icons';

const slugs = [
  'react',
  'nextdotjs',
  'typescript',
  'javascript',
  'nodedotjs',
  'express',
  'socketdotio',
  'tailwindcss',
  'mongodb',
  'mysql',
  'redis',
  'docker',
  'vercel',
  'render',
  'git',
  'github',
  'githubactions',
  'postman',
  'jsonwebtokens',
  'html5',
  'css',
  'openjdk',
  'googlegemini',
  'openrouter',
  'vite',
  'framer',
  'mongoose',
];

const toKey = (slug) => `si${slug.charAt(0).toUpperCase()}${slug.slice(1)}`;

const linkedin = {
  title: 'LinkedIn',
  hex: '0A66C2',
  path: 'M20.447 20.452h-3.554v-5.569c0-1.328-.027-3.037-1.852-3.037-1.853 0-2.136 1.445-2.136 2.939v5.667H9.351V9h3.414v1.561h.046c.477-.9 1.637-1.85 3.37-1.85 3.601 0 4.267 2.37 4.267 5.455v6.286zM5.337 7.433a2.062 2.062 0 0 1-2.063-2.065 2.064 2.064 0 1 1 2.063 2.065zm1.782 13.019H3.555V9h3.564v11.452zM22.225 0H1.771C.792 0 0 .774 0 1.729v20.542C0 23.227.792 24 1.771 24h20.451C23.2 24 24 23.227 24 22.271V1.729C24 .774 23.2 0 22.222 0h.003z',
};

const icons = [
  ...slugs.map((slug) => {
    const icon = si[toKey(slug)];
    if (!icon) throw new Error(`simple-icons has no icon for "${slug}"`);
    return [slug, icon];
  }),
  ['linkedin', linkedin],
];

const entries = icons.map(
  ([slug, icon]) =>
    `export const ${toKey(slug)}: BrandIconData = { title: ${JSON.stringify(icon.title)}, hex: ${JSON.stringify(
      `#${icon.hex}`,
    )}, path: ${JSON.stringify(icon.path)} };`,
);

// One named export per icon keeps every mark individually tree-shakeable.
const file = `// Generated by scripts/generate-brand-icons.mjs — do not edit by hand.
// Brand marks from simple-icons (CC0). LinkedIn is not in simple-icons, so its mark is inlined.

export type BrandIconData = { title: string; hex: string; path: string };

${entries.join('\n')}
`;

await writeFile(new URL('../src/components/icons/brand-icons.ts', import.meta.url), file);
console.log(`Wrote ${icons.length} brand icons`);
